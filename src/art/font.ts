const CW = 6, CH = 8, PER_ROW = 16;

export function buildFont(): BitmapFont {
  const keys = Object.keys(G);
  const rows = Math.ceil(keys.length / PER_ROW);
  const canvas = document.createElement('canvas');
  canvas.width = PER_ROW * CW;
  canvas.height = rows * CH;
  const ctx = canvas.getContext('2d')!;
  const img = ctx.createImageData(canvas.width, canvas.height);
  const glyphs: Record<string, Glyph> = {};
  keys.forEach((ch, i) => {
    const gx = (i % PER_ROW) * CW, gy = Math.floor(i / PER_ROW) * CH;
    glyphs[ch] = { x: gx, y: gy, w: CW, h: CH };
    G[ch].split(' ').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] !== '#') continue;
        const o = ((gy + y) * canvas.width + gx + x) * 4;
        img.data[o] = 255; img.data[o + 1] = 255; img.data[o + 2] = 255; img.data[o + 3] = 255;
      }
    });
  });
  ctx.putImageData(img, 0, 0);
  return { canvas, glyphs, lineHeight: 9 };
}
