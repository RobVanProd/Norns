/** Iterate set pixels of a glyph. */
export function glyphPixels(g: string[], fn: (x: number, y: number) => void) {
  for (let y = 0; y < g.length; y++) for (let x = 0; x < g[y].length; x++) if (g[y][x] === '#') fn(x, y);
}
